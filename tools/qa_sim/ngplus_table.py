# -*- coding: utf-8 -*-
"""New Game+ table from code truth (Session 23, S2): what each level does, which modifier does what, and whether anything reads each number.

Reads scripts/systems/new_game_plus.gd (the per-level constants and the accessors), content/ngp_modifiers.json (the modifiers and their knobs), and greps the
other scripts for the call sites of every accessor and knob. A number that is stored (shown, or kept in data) and read by nothing is a finding: the game would promise an effect it does not have.

usage: python tools/qa_sim/ngplus_table.py [--write docs/NGPLUS_TABLE.md] [--demo]
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
NGP = "scripts/systems/new_game_plus.gd"
SKIP = ("scripts/tools/", "scripts/security/")
# accessor -> the per-level constant it scales with (None: a modifier knob)
ACCESSORS = {
    "get_xp_multiplier": "XP_MULTIPLIER_PER_NG", "get_enemy_damage_multiplier": "ENEMY_DAMAGE_MULTIPLIER_PER_NG", "get_enemy_hp_multiplier": "ENEMY_HP_MULTIPLIER_PER_NG",
    "get_player_damage_multiplier": "PLAYER_DAMAGE_MULTIPLIER_PER_NG", "get_loot_chance_multiplier": "LOOT_CHANCE_MULTIPLIER_PER_NG",
    "are_hints_enabled": None, "get_night_cycle_multiplier": None, "is_time_pressure_enabled": None, "get_extra_dark_districts": None,
}
# the keys of data/ng_plus_config.json, which nothing read; the file was deleted in v10 F6 (the integrity manifest regenerated)
STALE_CONFIG = {"ng_plus_enemy_mult", "ng_plus_xp_mult", "unique_achievements"}


def lines_of(rel):
    return (ROOT / rel).read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").split("\n")


def constants():
    text = "\n".join(lines_of(NGP))
    found = {name: float(value) for name, value in re.findall(r"const (\w+_PER_NG) = ([\d.]+)", text)}
    found["MAX_NG_PLUS"] = float(re.search(r"const MAX_NG_PLUS = (\d+)", text).group(1))
    return found


def callers(pattern):
    out = []
    for f in sorted((ROOT / "scripts").rglob("*.gd")):
        rel = f.relative_to(ROOT).as_posix()
        if rel.startswith(SKIP) or rel == NGP:
            continue
        for number, text in enumerate(f.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            if re.search(pattern, text) and not text.lstrip().startswith("#"):
                out.append((rel, number, text.strip()))
    return out


def accessor_line(name):
    for number, text in enumerate(lines_of(NGP), 1):
        if text.startswith("func %s(" % name):
            return number
    return 0


def knob_sites(knob, accessors_for):
    sites = callers(r'get_modifier_(?:multiplier|toggle|additive)\(\s*"%s"' % re.escape(knob))
    for name in accessors_for.get(knob, []):
        sites += callers(r"\b%s\(" % name)
    return sites


def analyse():
    mods = json.loads((ROOT / "content" / "ngp_modifiers.json").read_text(encoding="utf-8"))["modifiers"]
    knobs = {}
    for m in mods:
        eff = m.get("effects", {})
        for k in list(eff.get("multipliers", {})) + list(eff.get("toggles", {})):
            knobs.setdefault(k, []).append(m["id"])
    # the NG+ script wraps some knobs in an accessor
    wrap = {"lore": ["get_xp_multiplier"], "loot": ["get_loot_chance_multiplier"], "hints": ["are_hints_enabled"], "cycle": ["get_night_cycle_multiplier"],
            "time_pressure": ["is_time_pressure_enabled"], "extra_dark_districts": ["get_extra_dark_districts"]}
    bad = []
    acc = {}
    for name in ACCESSORS:
        acc[name] = callers(r"\b%s\(" % name)
        if not acc[name]:
            bad.append("%s is read by nothing outside new_game_plus.gd" % name)
    ks = {}
    for k, ids in sorted(knobs.items()):
        ks[k] = knob_sites(k, wrap)
        if not ks[k]:
            bad.append("the knob %s of %s is read by nothing" % (k, ", ".join(ids)))
    return mods, knobs, acc, ks, bad


def write(path, mods, knobs, acc, ks, bad):
    const = constants()
    lines = ["# New Game+ table (Session 23)", "",
             "Generated by `python tools/qa_sim/ngplus_table.py --write docs/NGPLUS_TABLE.md`; the same tool is a static gate of `tools/check.sh`. The rule is in `docs/GDD.md` section 12.5; the code is `%s`; at most %d levels (`MAX_NG_PLUS`)." % (NGP, const["MAX_NG_PLUS"]), "",
             "## Per level", "", "| Level | XP | Enemy damage | Enemy health | Player damage | Loot chance |", "|---|---|---|---|---|---|"]
    for level in range(int(const["MAX_NG_PLUS"]) + 1):
        lines.append("| %d | x%.2f | x%.2f | x%.2f | x%.2f | x%.2f |" % (level, 1 + level * const["XP_MULTIPLIER_PER_NG"], 1 + level * const["ENEMY_DAMAGE_MULTIPLIER_PER_NG"], 1 + level * const["ENEMY_HP_MULTIPLIER_PER_NG"],
                                                                      1 + level * const["PLAYER_DAMAGE_MULTIPLIER_PER_NG"], 1 + level * const["LOOT_CHANCE_MULTIPLIER_PER_NG"]))
    lines += ["", "## Who reads each number", "", "| Accessor | Defined | First reader |", "|---|---|---|"]
    for name, sites in acc.items():
        first = "`%s` at `%s:%d`" % (name, sites[0][0], sites[0][1]) if sites else "nothing"
        lines.append("| `%s` | `%s` at `%s:%d` | %s |" % (name, name, NGP, accessor_line(name), first))
    lines += ["", "## Modifiers (one per level, `content/ngp_modifiers.json`)", "", "| Modifier | Effects | Excludes |", "|---|---|---|"]
    for m in mods:
        eff = m.get("effects", {})
        text = ", ".join("%s x%s" % (k, v) for k, v in eff.get("multipliers", {}).items()) + ("; " if eff.get("multipliers") and eff.get("toggles") else "") + ", ".join("%s = %s" % (k, str(v).lower()) for k, v in eff.get("toggles", {}).items())
        lines.append("| %s | %s | %s |" % (m["id"], text, ", ".join(m.get("exclusive_with", [])) or "-"))
    lines += ["", "## Who reads each modifier knob", "", "| Knob | Modifier | First reader |", "|---|---|---|"]
    for k, ids in sorted(knobs.items()):
        site = ks[k][0] if ks[k] else None
        lines.append("| %s | %s | %s |" % (k, ", ".join(ids), "`%s` at `%s:%d`" % (re.sub(r"\s+", " ", site[2])[:48].replace("`", "'"), site[0], site[1]) if site else "nothing"))
    lines += ["", "## Stored and read by nothing", "",
              "Nothing is stored and read by nothing: `data/ng_plus_config.json` (it kept `%s` and a list of achievement names, and no script opened it; the rule above is in the constants of the script) was deleted in v10 F6." % "`, `".join(sorted(STALE_CONFIG)),
              "", "Findings: %s." % ("none: every number the game shows or stores for New Game+ is read by a script" if not bad else "; ".join(bad))]
    pathlib.Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv):
    if "--demo" in argv:
        assert re.search(r'get_modifier_(?:multiplier|toggle|additive)\(\s*"x"', 'NewGamePlus.get_modifier_toggle("x", true)')
        assert not re.search(r'get_modifier_(?:multiplier|toggle|additive)\(\s*"x"', 'NewGamePlus.get_modifier_toggle("y", true)')
        print("ngplus_table demo: a knob read is found and another knob's read is not")
        return 0
    mods, knobs, acc, ks, bad = analyse()
    for line in bad:
        print("FAIL", line)
    if "--write" in argv:
        write(argv[argv.index("--write") + 1], mods, knobs, acc, ks, bad)
    print("ngplus_table: %d modifier(s), %d knob(s), %d accessor(s), %d finding(s)" % (len(mods), len(knobs), len(acc), len(bad)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
