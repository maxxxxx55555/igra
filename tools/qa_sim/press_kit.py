# -*- coding: utf-8 -*-
"""Press kit (Session 23, S1): store/PRESS_KIT.md written from the code, so its numbers cannot drift from the game.

The numbers come from listing_audit.truth() (districts, monsters, endings, languages, achievements, daily templates, music layers), the age estimate from store/IARC_ANSWERS.md, the picture list from
the files on disk (size and pixels). `--check` fails when the file is not what `--write` would write now.

usage: python tools/qa_sim/press_kit.py [--write store/PRESS_KIT.md] [--check]
"""
import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "qa_sim"))
import listing_audit  # noqa: E402

PICTURES = [
    ("Icon", "store/icon-512.png"), ("Feature graphic", "store/feature-graphic.png"),
    ("Press header (art)", "store/trailer/presskit_1600x900.png"), ("Still: first light (art)", "store/trailer/still_first_light_1920x1080.png"),
]


def png_size(path):
    with open(path, "rb") as f:
        head = f.read(24)
    return struct.unpack(">II", head[16:24]) if head[:8] == b"\x89PNG\r\n\x1a\n" else (0, 0)


def build():
    facts = listing_audit.truth()
    data = listing_audit.parse((ROOT / "store" / "listing.md").read_text(encoding="utf-8").replace("\r\n", "\n"))
    en = data["en"]
    lines = [
        "# Press kit: Last Streetlight", "",
        "Generated by `python tools/qa_sim/press_kit.py --write store/PRESS_KIT.md` from the code (`--check` is a static gate); it replaces `store/press-kit.md`, whose numbers were counted by hand in September.",
        "Spoiler ceiling: the first three districts and the lit power station; no ending text, no identity of the Architect.", "",
        "## Fact sheet", "",
        "- **Title:** Last Streetlight", "- **Tagline:** Restore the light. Every streetlight is life.", "- **Short description:** %s" % en["short"],
        "- **Genre:** stealth-horror first-person shooter, single player, offline",
        "- **Platforms:** Android (touch controls, double-tap dodge) and PC (keyboard and mouse); one game, one save format, export and import between devices, no account, no server",
        "- **Price:** free; no ads and no purchases in this build (`store/IARC_ANSWERS.md`, `docs/PRIVACY_AUDIT.md`)",
        "- **Engine:** Godot (MIT licence), the `gl_compatibility` renderer",
        "- **Age rating:** an estimate of PEGI 16 / ESRB Teen; the rating is issued by IARC after the owner answers the questionnaire (`store/IARC_ANSWERS.md`)",
        "- **Languages:** %d" % facts["languages"], "",
        "## What the game holds (read from the code)", "",
        "| Number | What | Read from |", "|---|---|---|",
        "| %d | districts, relit one at a time and reached from the city map | `DistrictSceneFactory.DISTRICTS` |" % facts["districts"],
        "| %d | enemy types the game spawns, the final boss among them | `EnemyPool.ROSTER_BY_DISTRICT`, `FinaleDirector` |" % facts["monsters"],
        "| %d | endings | `EndingsManager.ENDING_DATA` |" % facts["endings"],
        "| %d | achievements | `AchievementManager.ACHIEVEMENTS` |" % facts["achievements"],
        "| %d | daily challenges, with 7, 30 and 100 day streak bonuses | `content/daily_challenges.json` |" % facts["daily"],
        "| %d | adaptive music layers (dark, lit, two threat levels, action) | `MusicManager.LAYERS` |" % facts["music layers"],
        "| %d | languages | `data/i18n/` |" % facts["languages"], "",
        "## Pictures on disk", "", "| Picture | File | Pixels | Bytes |", "|---|---|---|---|",
    ]
    frames = sorted((ROOT / "docs" / "stills" / "store").glob("*.png"))
    for name, rel in PICTURES + [("Screenshot: " + re.sub(r"^\d+_|(_after)?_[0-9a-f]{7,}_\d{8}T\d{6}Z$", "", f.stem).replace("_", " "), f.relative_to(ROOT).as_posix()) for f in frames]:
        path = ROOT / rel
        if path.exists():
            w, h = png_size(path)
            lines.append("| %s | `%s` | %d x %d | %d |" % (name, rel, w, h, path.stat().st_size))
        else:
            lines.append("| %s | `%s` | missing | - |" % (name, rel))
    lines += ["", "The `Screenshot` rows are frames the engine drew, in `docs/stills/store/`, each named with the commit and the UTC time it was shot at. The art of `store/screenshots/` and the two rows marked `(art)` are painted or composed pictures (AI images, a programmatic composite): marketing art, not screenshots, and not for the screenshot slots of a store page. The recipes to shoot frames again are in `store/SCREENSHOT_RECIPES.md`.", "",
              "## For a reviewer", "",
              "1. A review copy is the signed bundle of `docs/RELEASE_ARTIFACTS.md`, installed from a closed test track.",
              "2. Contact: **[contact email / support URL]** (the owner fills it; it is the same address as in `docs/PRIVACY_POLICY_FINAL.md`).",
              "3. Trailer: the script is `store/TRAILER_SCRIPT.md`; no video exists yet.", ""]
    return "\n".join(lines)


def main(argv):
    text = build()
    if "--write" in argv:
        pathlib.Path(argv[argv.index("--write") + 1]).write_text(text, encoding="utf-8")
    if "--check" in argv:
        current = (ROOT / "store" / "PRESS_KIT.md").read_text(encoding="utf-8").replace("\r\n", "\n") if (ROOT / "store" / "PRESS_KIT.md").exists() else ""
        if current != text:
            print("FAIL store/PRESS_KIT.md is not what the code says now: run with --write")
            return 1
    print("press_kit: %d line(s)" % len(text.splitlines()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
