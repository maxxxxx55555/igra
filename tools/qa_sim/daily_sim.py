# -*- coding: utf-8 -*-
"""Daily challenge simulation (Session 23, S2): the templates the game loads, the signals that move them, the streak tiers.

It reads the file that scripts/systems/daily_challenge_manager.gd loads (content/daily_challenges.json when it exists, else data/daily_challenges.json), the types the manager
ticks, and the signals of scripts/events/event_bus.gd, then plays 120 consecutive days in a model of the manager and the streak rule of SaveSystem.increment_daily_streak.
Findings: a template whose type nothing ticks, whose signal the bus does not declare or whose target cannot be reached; a streak tier that no run of days pays.

usage: python tools/qa_sim/daily_sim.py [--write docs/DAILY_SIM.md] [--demo]
"""
import collections
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
MANAGER = ROOT / "scripts" / "systems" / "daily_challenge_manager.gd"
BUS = ROOT / "scripts" / "events" / "event_bus.gd"
SAVE = ROOT / "scripts" / "core" / "save_system.gd"
# What one day can offer of each countable thing: the districts, the secrets of content/secrets.json, the lamps of a district (48 poles) times the districts, minutes in a day.
CAP = {"restore_districts": 11, "find_secrets": None, "light_streets": 11 * 48, "play_minutes": 24 * 60, "kill_enemies": None, "photo_subject": None, "no_flashlight_segment": None}
DAYS = 120


def load():
    path = ROOT / "content" / "daily_challenges.json"
    legacy = ROOT / "data" / "daily_challenges.json"
    used = path if path.exists() else legacy
    return used, json.loads(used.read_text(encoding="utf-8")), json.loads(legacy.read_text(encoding="utf-8"))


def ticked_types():
    text = MANAGER.read_text(encoding="utf-8")
    return set(re.findall(r'_tick\("([a-z_]+)"', text)), re.findall(r"STREAK_MULTIPLIERS: Array = (\[\[.*?\]\])", text)


def declared_signals():
    return set(re.findall(r"^signal (\w+)", BUS.read_text(encoding="utf-8"), re.M))


def streak_rule():
    text = SAVE.read_text(encoding="utf-8").replace("\r\n", "\n")
    m = re.search(r"func increment_daily_streak\(\) -> void:\n(.*?)\n\n", text, re.S)
    gap = re.search(r"now - last > 86400 \* (\d+)", m.group(1)) if m else None
    return int(gap.group(1)) if gap else None


def secrets_count():
    return len(json.loads((ROOT / "content" / "secrets.json").read_text(encoding="utf-8"))["secrets"])


def simulate(rewards, multipliers, base):
    """Completing every day: the streak, the payout per day and the days a milestone pays."""
    streak, paid, milestones = 0, 0, []
    for day in range(1, DAYS + 1):
        streak += 1
        mult = next((m for d, m in multipliers if streak >= d), 1.0)
        paid += round(base * mult)
        for row in rewards:
            if streak == row["days"]:
                paid += row["reward"]
                milestones.append(day)
    return paid, milestones


def findings(used, data, ticks, signals, gap):
    out = []
    cap = dict(CAP)
    cap["find_secrets"] = None
    types = collections.Counter(t["type"] for t in data["templates"])
    for t in data["templates"]:
        if t["type"] not in ticks and t["type"] not in ("play_minutes", "no_flashlight_segment"):
            out.append("DEAD %s: nothing ticks the type %s" % (t["id"], t["type"]))
        sig = t.get("requires_signal", "")
        if sig.startswith("EventBus.") and sig.split(".", 1)[1] not in signals:
            out.append("DEAD %s: the bus declares no signal %s" % (t["id"], sig))
        limit = cap.get(t["type"])
        if limit is not None and t["target"] > limit:
            out.append("UNREACHABLE %s: target %d is over the %d a day can offer" % (t["id"], t["target"], limit))
        if t["target"] < 1:
            out.append("DEAD %s: target %d" % (t["id"], t["target"]))
    ids = [t["id"] for t in data["templates"]]
    if len(ids) != len(set(ids)):
        out.append("DUPLICATE template id")
    if gap is None:
        out.append("the streak rule of SaveSystem.increment_daily_streak was not found")
    return out, types


def report(used, data, legacy, ticks, signals, gap, bad, types):
    paid, milestones = simulate(data["streak_rewards"], [(7, 3.0), (5, 2.0), (3, 1.5)], 30)
    lines = [
        "# Daily challenge simulation (Session 23)",
        "",
        "Generated by `python tools/qa_sim/daily_sim.py --write docs/DAILY_SIM.md`. The game loads `%s` (%d templates); the older `data/daily_challenges.json` it falls back to has %d." % (used.relative_to(ROOT).as_posix(), len(data["templates"]), len(legacy["templates"])),
        "",
        "| Type | Templates | Target min to max | Reward min to max | Ticked by |",
        "|---|---|---|---|---|",
    ]
    for kind, n in sorted(types.items()):
        rows = [t for t in data["templates"] if t["type"] == kind]
        lines.append("| %s | %d | %d to %d | %d to %d | %s |" % (kind, n, min(t["target"] for t in rows), max(t["target"] for t in rows), min(t["reward"] for t in rows), max(t["reward"] for t in rows),
                                                                 "`_tick(\"%s\")`" % kind if kind in ticks else "the manager's `_process`"))
    lines += [
        "",
        "Signal types: %d. Streak rule: a completion more than %s days after the last one starts the streak again (`SaveSystem.increment_daily_streak`)." % (len(types), gap),
        "Playing %d consecutive days with a 30-coin challenge pays %d coins in all; the streak bonuses of %s fall on days %s." % (DAYS, paid, ", ".join(str(r["reward"]) for r in data["streak_rewards"]), ", ".join(str(m) for m in milestones)),
        "Findings: %s." % ("none" if not bad else "; ".join(bad)),
    ]
    return "\n".join(lines) + "\n"


def main(argv):
    if "--demo" in argv:
        data = {"templates": [{"id": "x", "type": "ghost", "target": 1, "reward": 1, "requires_signal": "EventBus.nope"}, {"id": "y", "type": "restore_districts", "target": 99, "reward": 1}], "streak_rewards": []}
        bad, _ = findings(None, data, {"kill_enemies"}, {"a"}, 2)
        assert any(b.startswith("DEAD x: nothing ticks") for b in bad) and any("declares no signal" in b for b in bad) and any(b.startswith("UNREACHABLE y") for b in bad)
        _, miles = simulate([{"days": 7, "reward": 1}, {"days": 30, "reward": 1}, {"days": 100, "reward": 1}], [], 1)
        assert miles == [7, 30, 100]
        print("daily_sim demo: a dead type, a missing signal, an unreachable target and the three streak tiers are all found")
        return 0
    used, data, legacy = load()
    ticks, _ = ticked_types()
    bad, types = findings(used, data, ticks, declared_signals(), streak_rule())
    if secrets_count() < 24:
        bad.append("the secrets file holds %d, fewer than the 24 a find_secrets target can ask for" % secrets_count())
    for line in bad:
        print("FAIL", line)
    text = report(used, data, legacy, ticks, declared_signals(), streak_rule(), bad, types)
    if "--write" in argv:
        pathlib.Path(argv[argv.index("--write") + 1]).write_text(text, encoding="utf-8")
    print("daily_sim: %d template(s) of %s, %d type(s), %d finding(s)" % (len(data["templates"]), used.relative_to(ROOT).as_posix(), len(types), len(bad)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
