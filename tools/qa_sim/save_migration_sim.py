# -*- coding: utf-8 -*-
"""Save migration matrix (Session 23, S2): what scripts/core/save_system.gd does with a save of each generation and with each fault.

The engine side is the closeout check SAVEMIG (scripts/tools/rc16/s2_checks.gd): it writes each case to disk in the real envelope format and prints one "[savemig] case=" line with what
SaveSystem._read_validated made of it. This tool holds those lines against an expectation table written a second time here, reads the constants and functions from the script (file:line),
and writes the matrix.

usage: python tools/qa_sim/save_migration_sim.py --log FILE [--write docs/SAVE_MIGRATION_MATRIX.md] [--demo]
       python tools/qa_sim/save_migration_sim.py --static     (only the constants of the script, for the static battery)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SAVE = "scripts/core/save_system.gd"
# id: (loaded, source, progress kept)
EXPECT = {
    "g0": (True, "main", True), "g1": (True, "main", True), "g2": (True, "main", True), "g3": (True, "main", True), "g4": (False, "none", False),
    "f1": (False, "none", False), "f2": (False, "none", False), "f3": (False, "none", False), "f4": (False, "none", False), "f5": (False, "none", False),
    "p1": (True, "main", False), "p2": (True, "main", False),
    "b1": (True, "bak", True), "b2": (True, "bak2", True), "b3": (True, "bak3", True), "b4": (False, "none", False), "b5": (True, "main", True), "b6": (True, "bak", True),
}
LINE = re.compile(r"\[savemig\] case=(\w+) \| (.*?) \| loaded=(\w+) source=(\w+) progress_kept=(\w+) version=(\S+) quarantined=(\w+)")
WORDS = {"main": "the main file", "bak": "the newest backup (.bak)", "bak2": "the second backup (.bak2)", "bak3": "the oldest backup (.bak3)", "none": "nothing"}


def script_facts():
    lines = (ROOT / SAVE).read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")

    def find(pattern):
        for number, text in enumerate(lines, 1):
            if re.search(pattern, text):
                return number
        return 0

    facts = {
        "version": (int(re.search(r"const SAVE_VERSION: int = (\d+)", "\n".join(lines)).group(1)), find(r"const SAVE_VERSION")),
        "depth": (int(re.search(r"const BACKUP_DEPTH: int = (\d+)", "\n".join(lines)).group(1)), find(r"const BACKUP_DEPTH")),
        "envelope": find(r"func _read_envelope"), "progress": find(r"func _verify_progress"), "migrate": find(r"func _migrate"), "validated": find(r"func _read_validated"),
        "rotate": find(r"func _rotate_backups"), "newer": find(r'int\(data\.get\("version", 0\)\) > SAVE_VERSION'),
    }
    return facts


def parse(log_text):
    return {m.group(1): (m.group(2), m.group(3) == "true", m.group(4), m.group(5) == "true", m.group(6), m.group(7) == "true") for m in LINE.finditer(log_text)}


def findings(rows, facts):
    out = []
    if facts["version"][0] != 3 or facts["depth"][0] != 3:
        out.append("the script changed: SAVE_VERSION %d, BACKUP_DEPTH %d (the matrix and the check are written for 3 and 3)" % (facts["version"][0], facts["depth"][0]))
    if rows is None:
        return out
    for case, (loaded, source, kept) in EXPECT.items():
        if case not in rows:
            out.append("case %s did not run" % case)
            continue
        _, got_loaded, got_source, got_kept, _, _ = rows[case]
        if (got_loaded, got_source, got_kept) != (loaded, source, kept):
            out.append("case %s: the loader gave loaded=%s source=%s progress_kept=%s, the matrix says loaded=%s source=%s progress_kept=%s" % (case, got_loaded, got_source, got_kept, loaded, source, kept))
    return out


def write(path, rows, facts):
    lines = [
        "# Save migration matrix (Session 23)",
        "",
        "Generated by `python tools/qa_sim/save_migration_sim.py --log <closeout log> --write docs/SAVE_MIGRATION_MATRIX.md` from the `[savemig]` lines of the closeout check SAVEMIG (`scripts/tools/rc16/s2_checks.gd`), which writes each case to disk",
        "in the real envelope and calls `SaveSystem._read_validated`. The script says: `SAVE_VERSION` is %d at `%s:%d`, `BACKUP_DEPTH` is %d at `%s:%d`; a file is read by `_read_envelope` at `%s:%d`, its district and progress data are held by"
        % (facts["version"][0], SAVE, facts["version"][1], facts["depth"][0], SAVE, facts["depth"][1], SAVE, facts["envelope"]),
        "`_verify_progress` at `%s:%d`, a version below the current one is raised by `_migrate` at `%s:%d` (the versions 1 to 3 only added keys), the backups are tried by `_read_validated` at `%s:%d` and rotated by `_rotate_backups` at `%s:%d`;"
        % (SAVE, facts["progress"], SAVE, facts["migrate"], SAVE, facts["validated"], SAVE, facts["rotate"]),
        "a save newer than the build is refused by the line at `%s:%d`." % (SAVE, facts["newer"]),
        "",
        "| Case | What is on disk | Loaded | From | District and progress data | Version after | Main file renamed to .corrupt |",
        "|---|---|---|---|---|---|---|",
    ]
    for case in EXPECT:
        title, loaded, source, kept, version, quarantined = rows[case]
        lines.append("| %s | %s | %s | %s | %s | %s | %s |" % (case, title, "yes" if loaded else "no", WORDS[source], "kept" if kept else ("reset to empty" if loaded else "-"), re.sub(r"\.0$", "", version) if loaded else "-", "yes" if quarantined else "no"))
    lines += [
        "",
        "Reading: a save of any older version loads and becomes the current version (no key was ever removed or renamed, so there is nothing to transform); a save newer than the build is refused, and the backups are tried, so a player who",
        "installs an older build gets the last backup that the older build can read (case b6); a file without a valid signature never loads (cases f1 to f3: the pre-signature format is refused on purpose, `docs/KNOWN_ISSUES.md`);",
        "a file whose district and progress data fail their own signature loads with both reset (cases p1, p2); the backups are tried newest first, and a main file that no backup can replace is renamed so the next start is clean (case b4).",
    ]
    pathlib.Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv):
    if "--demo" in argv:
        sample = "[savemig] case=g1 | version 1 | loaded=true source=main progress_kept=true version=3 quarantined=false\n[savemig] case=f1 | no hmac | loaded=false source=none progress_kept=false version=0 quarantined=true"
        rows = parse(sample)
        assert rows["g1"][1] is True and rows["f1"][5] is True
        facts = {"version": (3, 4), "depth": (3, 9)}
        out = findings({"g1": rows["g1"], "f1": ("x", True, "main", False, "0", False)}, facts)
        assert any(o.startswith("case f1:") for o in out) and any("did not run" in o for o in out)
        print("save_migration_sim demo: a parsed line, a wrong outcome and a case that did not run are all found")
        return 0
    facts = script_facts()
    rows = None
    if "--log" in argv:
        rows = parse(pathlib.Path(argv[argv.index("--log") + 1]).read_text(encoding="utf-8", errors="replace"))
    bad = findings(rows, facts)
    for line in bad:
        print("FAIL", line)
    if "--write" in argv and rows is not None and not bad:
        write(argv[argv.index("--write") + 1], rows, facts)
    print("save_migration_sim: SAVE_VERSION %d, BACKUP_DEPTH %d, %s, %d finding(s)" % (facts["version"][0], facts["depth"][0], "%d case(s) read" % len(rows) if rows is not None else "static only", len(bad)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
